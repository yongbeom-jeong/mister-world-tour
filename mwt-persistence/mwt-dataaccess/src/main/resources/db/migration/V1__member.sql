-- Member Management: 회원 (설계 4장 Member)
-- 아이디는 대소문자를 무시하고 중복 금지: 소문자로 바꾼 username_key 에 유일 제약
CREATE TABLE member (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(20)  NOT NULL,
    username_key  VARCHAR(20)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    name          VARCHAR(50)  NOT NULL,
    address       VARCHAR(200) NOT NULL DEFAULT '',
    contact       VARCHAR(20)  NOT NULL,
    role          VARCHAR(10)  NOT NULL,
    date_joined   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_member_username_key UNIQUE (username_key),
    CONSTRAINT ck_member_role CHECK (role IN ('CUSTOMER', 'STAFF'))
);
