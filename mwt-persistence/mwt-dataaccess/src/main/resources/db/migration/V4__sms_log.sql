-- SMS Notification: 문자 1건(수신자 1명)의 발송 기록. 자동 재시도와 직원 재발송 결과를 같은 행에 누적한다.
-- 수신 고객·상품은 다른 서브시스템의 값이라 id·이름 값으로 보관한다 (지워져도 기록은 남음).
CREATE TABLE sms_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id      BIGINT,
    recipient_name VARCHAR(50)  NOT NULL,
    contact        VARCHAR(20)  NOT NULL DEFAULT '',
    product_id     BIGINT,
    product_name   VARCHAR(100) NOT NULL DEFAULT '',
    message        TEXT         NOT NULL,
    status         VARCHAR(10)  NOT NULL,
    attempt_count  INTEGER      NOT NULL DEFAULT 0,
    last_error     TEXT         NOT NULL DEFAULT '',
    provider_ref   VARCHAR(100) NOT NULL DEFAULT '',
    resend_count   INTEGER      NOT NULL DEFAULT 0,
    resent_by_id   BIGINT REFERENCES member (id) ON DELETE SET NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_sms_log_status_created ON sms_log (status, created_at DESC);
