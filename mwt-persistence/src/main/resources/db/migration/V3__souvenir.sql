-- Souvenir Management: 기념품·입고·출발 확정 차감 (설계 06장)
-- 품목 이름은 대소문자를 무시하고 중복 금지 (숨긴 품목 포함): 소문자 name_key 에 유일 제약

CREATE TABLE souvenir (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(50) NOT NULL,
    name_key       VARCHAR(50) NOT NULL,
    theme          VARCHAR(10) NOT NULL,
    stock_quantity INTEGER     NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    is_active      BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_souvenir_name_key UNIQUE (name_key)
);

-- 한 번의 입고. request_key 로 같은 입고의 재시도를 구별해 재고가 두 번 늘지 않게 한다.
CREATE TABLE stock_receipt (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    souvenir_id BIGINT      NOT NULL REFERENCES souvenir (id),
    employee_id BIGINT      NOT NULL REFERENCES member (id),
    quantity    INTEGER     NOT NULL CHECK (quantity >= 1),
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    request_key VARCHAR(64) NOT NULL,
    stock_after INTEGER     NOT NULL CHECK (stock_after >= 0),
    CONSTRAINT uq_stock_receipt_request_key UNIQUE (request_key)
);

-- 출발 확정으로 차감한 기념품. (품목, 신청)마다 1행이라 두 번 차감되지 않는다.
CREATE TABLE stock_issue (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    souvenir_id    BIGINT  NOT NULL REFERENCES souvenir (id),
    application_id BIGINT  NOT NULL REFERENCES travel_application (id),
    quantity       INTEGER NOT NULL CHECK (quantity >= 0),
    issued_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    stock_after    INTEGER NOT NULL CHECK (stock_after >= 0),
    CONSTRAINT uq_issue_per_application UNIQUE (souvenir_id, application_id)
);

