-- Travel Management: 상품·신청·여행자·완료 이력 (설계 05장). 금액은 원 단위 정수.

CREATE TABLE travel_product (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(100) NOT NULL,
    destination      VARCHAR(100) NOT NULL DEFAULT '',
    description      TEXT         NOT NULL DEFAULT '',
    image            VARCHAR(200),
    theme            VARCHAR(10)  NOT NULL,
    tour_level       VARCHAR(10)  NOT NULL,
    base_price       INTEGER      NOT NULL CHECK (base_price >= 0),
    travel_days      INTEGER      NOT NULL CHECK (travel_days >= 0),
    departure_date   DATE         NOT NULL,
    theme_service    VARCHAR(100) NOT NULL,
    hotel_level      VARCHAR(10)  NOT NULL,
    transport        VARCHAR(20)  NOT NULL,
    meal             VARCHAR(10)  NOT NULL,
    departure_status VARCHAR(10),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_travel_product_departure ON travel_product (departure_date, id);

CREATE TABLE travel_application (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id        BIGINT       NOT NULL REFERENCES member (id),
    product_id       BIGINT       NOT NULL REFERENCES travel_product (id),
    hotel_level      VARCHAR(10)  NOT NULL,
    transport        VARCHAR(20)  NOT NULL,
    meal             VARCHAR(10)  NOT NULL,
    extra_drinks     VARCHAR(200) NOT NULL DEFAULT '',
    unit_price       INTEGER      NOT NULL CHECK (unit_price >= 0),
    subtotal         INTEGER      NOT NULL CHECK (subtotal >= 0),
    discount_amount  INTEGER      NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    final_amount     INTEGER      NOT NULL CHECK (final_amount >= 0),
    request_key      VARCHAR(64)  NOT NULL,
    submitted_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    departure_status VARCHAR(10),
    cancelled_at     TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_travel_application_request_key UNIQUE (request_key)
);
CREATE INDEX ix_travel_application_member ON travel_application (member_id);
CREATE INDEX ix_travel_application_product ON travel_application (product_id);

CREATE TABLE traveler (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT      NOT NULL REFERENCES travel_application (id) ON DELETE CASCADE,
    name           VARCHAR(50) NOT NULL,
    contact        VARCHAR(20) NOT NULL DEFAULT '',
    is_applicant   BOOLEAN     NOT NULL DEFAULT FALSE
);
CREATE INDEX ix_traveler_application ON traveler (application_id);

CREATE TABLE travel_history (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id           BIGINT       NOT NULL REFERENCES member (id) ON DELETE CASCADE,
    completed_travel_id VARCHAR(64)  NOT NULL,
    product_name        VARCHAR(100) NOT NULL,
    tour_level          VARCHAR(10)  NOT NULL,
    travel_days         INTEGER      NOT NULL,
    price               INTEGER      NOT NULL,
    completed           BOOLEAN      NOT NULL DEFAULT FALSE,
    completed_at        DATE,
    CONSTRAINT uq_member_completed_travel UNIQUE (member_id, completed_travel_id)
);
